import { NOTES, TOPICS, USAGE } from './help.js';

const GENERATED = '<!-- Generated by `npm run docs`. Edit src/help.ts or the MCP tool descriptions instead. -->';
/** Command reference, one section per help topic, from the same source as the CLI help. */
export function commandsMarkdown(): string {
  return [GENERATED, '', '# CLI command reference', '', `\`${USAGE}\``, '',
    'Run `apple-connect-mcp help <topic>` or `apple-connect-mcp <command> --help` for the same text in a terminal.', '',
    '## Topics', '', ...TOPICS.map(t => `- [${t.title}](#${t.id}): ${t.summary}`), '',
    ...TOPICS.flatMap(t => [`<a id="${t.id}"></a>`, `## ${t.title}`, '', t.summary + (t.note ? ` ${t.note.replace(/^./, c => c.toUpperCase())}.` : ''), '', '```text', t.commands.trimEnd(), '```', '']),
    '## Notes', '', ...NOTES.split('\n').map(line => line), ''].join('\n');
}
export interface ToolInfo { name: string; description?: string; annotations?: { readOnlyHint?: boolean } }
/** MCP tool reference, grouped into read-only tools and the few that save local plans. */
export function toolsMarkdown(tools: ToolInfo[]): string {
  const row = (t: ToolInfo) => `| \`${t.name}\` | ${(t.description ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')} |`;
  const sorted = [...tools].sort((a, b) => a.name.localeCompare(b.name));
  const reads = sorted.filter(t => t.annotations?.readOnlyHint === true);
  const others = sorted.filter(t => t.annotations?.readOnlyHint !== true);
  return [GENERATED, '', '# MCP tools', '', `${tools.length} tools. Read-only tools never change App Store Connect. The others save a local plan or run a reviewed one; see [Safety model](safety.md).`, '',
    `## Read-only (${reads.length})`, '', '| Tool | What it does |', '| --- | --- |', ...reads.map(row), '',
    `## Plans and workflows (${others.length})`, '', '| Tool | What it does |', '| --- | --- |', ...others.map(row), ''].join('\n');
}
